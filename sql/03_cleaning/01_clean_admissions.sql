-- CHECK IF THE DATES IN doa WHERE CORRECTLY FORMATED
SELECT COUNT(*) AS month_mismatches
FROM clean.hdhi_admission_cleaned c
JOIN staging.hdhi_admission_raw s
    ON c.sno = s.sno::INTEGER
WHERE TO_CHAR(c.doa, 'Mon-YY') <> s.month_year;